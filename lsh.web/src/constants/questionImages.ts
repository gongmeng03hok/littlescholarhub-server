/**
 * Art for a single answer option, or undefined when its wording names nothing
 * we can draw. Emotion art (happy/sad/…) keeps priority — it is purpose-drawn.
 */
export function optionImage(optionText?: string, ctx?: ArtContext): any | undefined {
  if (!optionText) return undefined;
  const raw = optionText.toLowerCase().trim();
  const key = raw.replace(/[^a-zà-ÿ\s]/gi, "").trim();

  // exact word, then any word inside a short phrase ("light and warmth")
  const direct = OPTION_WORDS[key];
  if (direct) return resolve(direct, ctx);

  for (const word of key.split(/\s+/)) {
    const name = OPTION_WORDS[word];
    if (name) return resolve(name, ctx);
  }
  // phonics object photos (cat, dog, train …) double as option art
  const phon = PHONICS_WORD_IMAGES[key];
  if (phon) return phon;
  return undefined;
}

/** Which object rules still have no artwork at all — PNG or SVG. */
export function missingQuestionImages(): string[] {
  const wanted = new Set(OBJECT_RULES.map(([, name]) => name));
  return [...wanted].filter(name => !OBJECT_IMAGES[name] && !hasArt(name)).sort();
}

/** Which rules are still running on built-in SVG rather than a real render. */
export function svgFallbackImages(): string[] {
  const wanted = new Set(OBJECT_RULES.map(([, name]) => name));
  return [...wanted].filter(name => !OBJECT_IMAGES[name] && hasArt(name)).sort();
}
