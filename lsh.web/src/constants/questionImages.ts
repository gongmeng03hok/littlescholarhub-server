// ── Tailoring: culture track + age band ──────────────────────────────────────
// A name resolves to the most specific artwork that exists on disk:
//   holidays + zh track          → /art/holidays.zh.svg   (lantern)
//   apples   + TK–1              → /art/apples.tk.svg     (one big apple)
//   anything with no variant     → /art/holidays.svg      (neutral)

export interface ArtContext {
  /** Subject slug — phonics · reading · math · art · story · workbooks · logic · feelings · manners */
  subject?: string;
  /** Interest/topic slug — dinosaurs · space · ocean · animals · … */
  topic?: string;
  /** Grade number (0 = TK) or label, used for the age band */
  grade?: number | string;
  /** Culture track / language: zh · hi · es (en or absent = neutral art) */
  culture?: string;
  /** Free text such as a worksheet title ("Dinosaurs Manners - Grade TK") */
  title?: string;
}

/** TK–1 gets the simpler, chunkier variants; 4–6 the more detailed ones. */
function ageBand(grade?: number | string): string | undefined {
  if (grade === undefined || grade === null) return undefined;
  const n = typeof grade === "number" ? grade : parseGrade(String(grade));
  if (n === undefined) return undefined;
  if (n <= 1) return "tk";
  if (n >= 4) return "g46";
  return undefined;
}

function parseGrade(label: string): number | undefined {
  const t = label.toLowerCase();
  if (/\btk\b|transitional/.test(t)) return 0;
  if (/kinder|\bk\b/.test(t)) return 0;
  const m = t.match(/(\d+)/);
  return m ? Number(m[1]) : undefined;
}

const CULTURES = ["zh", "hi", "es"];

/** Subject slugs we ship guaranteed fallback art for. */
const SUBJECT_ART: Record<string, string> = {
  phonics: "subj_phonics", reading: "subj_reading", math: "subj_math",
  art: "subj_art", story: "subj_story", workbooks: "subj_workbooks",
  logic: "subj_logic", feelings: "subj_feelings", manners: "subj_manners",
};

/** Topic slugs (interest themes) that have their own art. */
const TOPIC_ART = ["animals", "dinosaurs", "space", "ocean", "fantasy",
                   "vehicles", "holidays", "sports", "nature"];

/** Return a scene/word illustration for a question, or undefined if none applies. */
export function questionImage(questionText?: string, hint?: string, ctx?: ArtContext): any | undefined {
  const hay = `${questionText ?? ""}  ${hint ?? ""}`;

  // 1 · Phonics: pull the target word out of the hint and look up its object image.
  const m = hint?.match(/the word is ['"]?([a-zA-Z]+)/i);
  if (m) {
    const word = m[1].toLowerCase();
    const img = PHONICS_WORD_IMAGES[word] ?? resolve(word, ctx);
    if (img) return img;
  }

  // 2 · Hand-authored scenes (feelings / manners) win where they exist.
  for (const [re, img] of SCENE_RULES) {
    if (re.test(hay)) return img;
  }

  // 2b · Otherwise the generated scene for this exact scenario, so no two
  //      prompts in a round share a picture.
  for (const [re, name] of GENERATED_SCENES) {
    if (re.test(hay) && hasArt(name)) return { uri: "/art/" + name + ".svg" };
  }

  // 3 · Object art: a dropped-in PNG first, else the built-in glassy SVG.
  for (const [re, name] of OBJECT_RULES) {
    if (re.test(hay)) {
      const img = resolve(name, ctx);
      if (img) return img;
    }
  }

  // 4 · Fall back to the worksheet's TOPIC (dinosaurs, ocean, …), from the
  //     context or parsed out of its title.
  const topic = ctx?.topic?.toLowerCase() ?? sniff(ctx?.title, TOPIC_ART);
  if (topic) {
    const img = resolve(topic, ctx);
    if (img) return img;
  }

  // 5 · Last resort — the SUBJECT. Every question belongs to one, so from here
  //     on a card is never left bare.
  const subject = ctx?.subject?.toLowerCase() ?? sniff(ctx?.title, Object.keys(SUBJECT_ART));
  if (subject && SUBJECT_ART[subject]) {
    const img = resolve(SUBJECT_ART[subject], ctx);
    if (img) return img;
  }

  // 6 · Cultural questions carry their own track art even with no subject.
  const culture = cultureOf(hay, ctx);
  if (culture) {
    const img = resolve("culture_" + culture, ctx);
    if (img) return img;
  }

  return undefined;
}

/** Find the first known slug mentioned in a free-text title. */
function sniff(title: string | undefined, slugs: string[]): string | undefined {
  if (!title) return undefined;
  const t = title.toLowerCase();
  return slugs.find(sl => t.includes(sl));
}

/** Which culture track a question belongs to, if any. */
function cultureOf(hay: string, ctx?: ArtContext): string | undefined {
  if (ctx?.culture && CULTURES.indexOf(ctx.culture) !== -1) return ctx.culture;
  if (/[一-鿿]|pinyin|tone|tang poem/i.test(hay)) return "zh";
  if (/gita|sanskrit|diwali|namaste/i.test(hay)) return "hi";
  if (/spanish|español|españa|fiesta|día de/i.test(hay)) return "es";
  return undefined;
}

/**
 * Most specific artwork wins:
 *   dropped-in PNG  →  <name>.<culture>  →  <name>.<ageBand>  →  <name>
 */
function resolve(name: string, ctx?: ArtContext): any | undefined {
  if (OBJECT_IMAGES[name]) return OBJECT_IMAGES[name];

  const culture = ctx?.culture && CULTURES.indexOf(ctx.culture) !== -1 ? ctx.culture : undefined;
  const band = ageBand(ctx?.grade ?? (ctx?.title ? parseGrade(ctx.title) : undefined));

  for (const candidate of [
    culture ? name + "." + culture : undefined,
    band ? name + "." + band : undefined,
    name,
  ]) {
    if (!candidate) continue;
    if (OBJECT_IMAGES[candidate]) return OBJECT_IMAGES[candidate];
    if (hasArt(candidate)) return { uri: "/art/" + candidate + ".svg" };
  }
  return undefined;
}

