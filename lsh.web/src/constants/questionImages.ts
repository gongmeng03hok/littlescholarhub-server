// ── Drop-in object registry ───────────────────────────────────────────────────
// Every PNG in assets/objects/ becomes available under its bare filename.
// require.context is a Metro feature (enabled in this Expo/expo-router app); the
// try/catch keeps the app running on any bundler that lacks it.
const OBJECT_IMAGES: Record<string, any> = (() => {
  const out: Record<string, any> = {};
  try {
    // @ts-ignore — require.context is provided by Metro, not by TS
    const ctx = require.context("../assets/objects", false, /\.(png|jpg|jpeg)$/);
    for (const key of ctx.keys()) {
      const name = key.replace(/^\.\//, "").replace(/\.(png|jpg|jpeg)$/i, "").toLowerCase();
      out[name] = ctx(key);
    }
  } catch {
    // No require.context (or no folder yet) — object art simply stays unmatched.
  }
  return out;
})();

