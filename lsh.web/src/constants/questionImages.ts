// Scene / word illustrations shown ABOVE questions (kids are visual).
// AI-generated 3D renders (Canva), matched by a keyword in the question text or
// hint — so no backend/API change is needed, it's purely a frontend enhancement.
//
// TWO kinds of art live here:
//
//  1. STATIC requires (`SCENE_RULES`, `PHONICS_WORD_IMAGES`) — the original sets.
//     Only require() images that actually exist in assets, or the bundler fails.
//
//  2. The `assets/objects/` DROP-IN folder — read with require.context, so a new
//     PNG is picked up by its FILENAME with no code change. Name the file after
//     the object (`apple.png`, `sun.png`, `dinosaur.png`) and the rules below
//     will find it. A rule pointing at a file that isn't there yet is harmless:
//     it just falls through, no image, no crash, no build break.
//     Prompts + the full filename list: docs/QUESTION_IMAGE_PROMPTS.md
//
//  3. `/art/<name>.svg` — the built-in glassy 3D illustrations, generated by
//     tools/gen-art.mjs into src/public/art/ and served as static files, so a
//     question is never left bare while the render set is filled in. A PNG of
//     the same name always WINS over the SVG.
//     (They must be files, not inline data URIs: react-native-web 0.21's
//     <Image> silently refuses to render a data:image/svg+xml source.)

